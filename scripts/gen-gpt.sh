#!/bin/sh
# SPDX-License-Identifier: MIT
# Generate the GPT-B layout for BOARD from a LOCAL GPT template (a GPT dump of the same board).
#   BOARD_GPT_TEMPLATE            path to the primary GPT dump (34 sectors, LBA 0..33). Set it in
#                                 config/local.env (git-ignored). It is never copied into the repo.
#   BOARD_GPT_TEMPLATE_SECONDARY  optional: secondary dump (last 33 sectors); enables extra self-tests.
# Kept entries are copied byte-identical (name, type GUID, unique GUID, LBAs, attributes). Dropped:
# boot (old), system, cache, recovery, userdata. Added: boot (64 MiB at the old 'system' start) and
# rootfs (old 'cache' start .. last usable LBA, rounded down to 4 KiB). CRCs are recomputed.
# Writes ONLY under out/ and work/. Never touches a device.
# Outputs (out/fw/): gpt-primary.bin (34 sectors), gpt-secondary.bin (33 sectors), gpt_both0.bin
# (= primary + secondary, fastboot "partition" format), layout-<BOARD>.env / .txt
. "$(dirname "$0")/common.sh"
command -v python3 >/dev/null || die "python3 not found"
command -v sfdisk >/dev/null || die "sfdisk not found (package fdisk)"
case "${EMMC_SECTORS:-}" in ''|*[!0-9]*) die "EMMC_SECTORS missing or not a number (boards/$BOARD/board.env)";; esac
[ "${SECTOR_SIZE:-512}" = 512 ] || die "only 512-byte sectors are supported"
[ -n "${BOARD_GPT_TEMPLATE:-}" ] || die "BOARD_GPT_TEMPLATE is not set. Point it at the primary GPT dump of board $BOARD (34 sectors, e.g. in config/local.env: BOARD_GPT_TEMPLATE=/path/to/gpt-primary.bin). The generator is template based and has no built-in layout."
[ -f "$BOARD_GPT_TEMPLATE" ] || die "BOARD_GPT_TEMPLATE='$BOARD_GPT_TEMPLATE' does not exist"
[ "$(stat -c %s "$BOARD_GPT_TEMPLATE")" -eq 17408 ] || die "BOARD_GPT_TEMPLATE must be exactly 17408 B (34 sectors)"
case "$BOARD_GPT_TEMPLATE" in "$ROOT"/*) die "BOARD_GPT_TEMPLATE must live OUTSIDE the repo ($ROOT)";; esac
PY="python3 -I $ROOT/scripts/gptool.py"
SEC_ARG=""; [ -n "${BOARD_GPT_TEMPLATE_SECONDARY:-}" ] && SEC_ARG="--template-secondary $BOARD_GPT_TEMPLATE_SECONDARY"
echo "board=$BOARD emmc_sectors=$EMMC_SECTORS template=$(basename "$BOARD_GPT_TEMPLATE") sha256=$(sha256sum "$BOARD_GPT_TEMPLATE" | cut -c1-16)..."

mkdir -p "$OUT/fw" "$WORK"
# $PY and $SEC_ARG are intentionally unquoted (word splitting); paths are validated above and contain no spaces
$PY generate --emmc "$EMMC_SECTORS" --template "$BOARD_GPT_TEMPLATE" --boot-uuid "$BOOT_PARTUUID" \
    --root-uuid "$ROOT_PARTUUID" --outdir "$OUT/fw" --board "$BOARD"

# Independent parse of the generated bytes: place both files in a sparse disk-sized image, read with sfdisk/sgdisk
T=$(mktemp -d "$WORK/gpt.XXXXXX"); trap 'rm -rf --one-file-system -- "${T:?}"' EXIT
D=$T/disk.img
truncate -s $((EMMC_SECTORS * 512)) "$D"
dd if="$OUT/fw/gpt-primary.bin" of="$D" bs=512 conv=notrunc status=none
dd if="$OUT/fw/gpt-secondary.bin" of="$D" bs=512 seek=$((EMMC_SECTORS - 33)) conv=notrunc status=none
if command -v sgdisk >/dev/null; then
    sgdisk -v "$D" | grep -q "No problems found" || { sgdisk -v "$D" >&2; die "sgdisk -v reports problems with the generated GPT"; }
    echo "sgdisk -v: No problems found"
fi
sfdisk -d "$D" | grep -v "^device:" | sed "s|$T/||g" > "$OUT/fw/layout-$BOARD.txt"
cd "$OUT/fw" && sha256sum gpt-primary.bin gpt-secondary.bin gpt_both0.bin
